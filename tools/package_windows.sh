#!/usr/bin/env bash
# Assemble the Windows player package as a local folder: dist/WilyWarsRecomp-win64/
#   MMWW-Setup.exe            one-click builder (picker -> toolchain -> build -> launch)
#   tools/GenesisRecomp.exe   the recompiler, built for Windows
#   src/                      project + engine sources (no ROM, no generated C)
#   shaders/                  librashader runtime + slang presets
# It refuses to finish if a ROM, a 2 MB image, or generated code got in.
# Usage: tools/package_windows.sh <llvm-mingw bin dir> <GenesisRecomp.exe> <shaders dir>
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LLVM="$1"; RECOMP_EXE="$2"; SHADERS="$3"
OUT="$ROOT/dist/WilyWarsRecomp-win64"
rm -rf "$OUT"; mkdir -p "$OUT/tools" "$OUT/src"

"$LLVM/x86_64-w64-mingw32-windres" -I "$ROOT/src/win32" "$ROOT/src/win32/app.rc" -O coff -o /tmp/mmww_setup_icon.o
"$LLVM/x86_64-w64-mingw32-clang" -O2 -static -o "$OUT/MMWW-Setup.exe" \
    "$ROOT/tools/setup/mmww_setup.c" "$ROOT/tools/setup/third_party/miniz/miniz.c" /tmp/mmww_setup_icon.o \
    -lurlmon -lcomdlg32 -lshell32
cp "$RECOMP_EXE" "$OUT/tools/GenesisRecomp.exe"

S="$OUT/src"
cp "$ROOT/CMakeLists.txt" "$ROOT/README.md" "$ROOT/LICENSE" "$ROOT/NOTICE.md" "$ROOT/SHADERS.md" "$S/"
cp "$ROOT/README.md" "$OUT/README.md"; cp "$ROOT/LICENSE" "$OUT/LICENSE.txt"; cp "$ROOT/NOTICE.md" "$OUT/NOTICE.md"
cp -r "$ROOT/cmake" "$ROOT/src" "$ROOT/vendor" "$ROOT/assets" "$S/"
mkdir -p "$S/game"
for f in "$ROOT"/game/*; do
  case "$f" in *.bin|*.md|*.gen|*.smd|*.rom) continue;; esac
  cp "$f" "$S/game/"
done
mkdir -p "$S/recomp-ui/src/third_party"
cp "$ROOT/recomp-ui/src/third_party/stb_truetype.h" "$S/recomp-ui/src/third_party/"
mkdir -p "$S/third_party/SDL2-mingw-2.28.5"
cp -r "$ROOT/third_party/SDL2-mingw-2.28.5/x86_64-w64-mingw32" "$S/third_party/SDL2-mingw-2.28.5/"
for f in COPYING.txt LICENSE.txt README.txt; do
  [ -f "$ROOT/third_party/SDL2-mingw-2.28.5/$f" ] && cp "$ROOT/third_party/SDL2-mingw-2.28.5/$f" "$S/third_party/SDL2-mingw-2.28.5/"
done
E="$S/segagenesisrecomp"; mkdir -p "$E/runner"
cp -r "$ROOT/segagenesisrecomp/cmake" "$ROOT/segagenesisrecomp/recompiler" "$E/"
cp "$ROOT"/segagenesisrecomp/LICENSE* "$ROOT/segagenesisrecomp/THIRD-PARTY-LICENSES.md" "$E/"
( cd "$ROOT/segagenesisrecomp/runner" && tar --exclude=external/SDL2 --exclude=external/SDL2-VC.zip -cf - . ) | ( cd "$E/runner" && tar -xf - )
rm -rf "$E/recompiler/build"*
( cd "$ROOT/segagenesisrecomp" && tar --exclude=.git --exclude="*/build*" --exclude=external/m68k-recomp-core/profiles/scc68070 -cf - external ) | ( cd "$E" && tar -xf - )
cp -r "$SHADERS" "$OUT/shaders"

cat > "$OUT/README.txt" <<'R'
Mega Man: The Wily Wars Recomp (Windows x64)

1. Double-click MMWW-Setup.exe.
2. Pick your own ROM: Mega Man - The Wily Wars (USA) (Mega Drive Mini / Genesis Mini),
   2,097,152 bytes, CRC32 0CD405DB. It never leaves your PC.
3. Setup downloads a portable compiler into toolchain\ (first time only, ~300 MB download, ~900 MB on disk,
   from the official llvm-mingw, CMake and Ninja GitHub releases), translates the
   game to C on your PC, builds it into game\ and starts it.

After that, MMWW-Setup.exe just starts the game. "MMWW-Setup.exe --rebuild" builds again.
In game: Esc / F12 / Guide button opens the side menu (shaders, filter, 16:9, save states).
This package contains no ROM and no code generated from one. setup.log has build output.
R

# Guard: no ROM, no 2 MB images, no generated code.
bad=0
while IFS= read -r -d '' f; do
  sz=$(stat -c %s "$f")
  if [ "$sz" -eq 2097152 ]; then echo "REFUSING: 2 MB file $f"; bad=1; fi
done < <(find "$OUT" -type f -print0)
if find "$OUT" \( -name '*.bin' -o -name 'mmww.md' -o -path '*/generated/*' -o -name 'mmww_part*.c' -o -name 'mmww_dispatch.c' -o -name 'mmww_cycles.c' -o -name 'mmww_layout.c' -o -name 'mmww_decls.h' \) | grep -q .; then
  echo 'REFUSING: ROM or generated files:'; find "$OUT" \( -name '*.bin' -o -path '*/generated/*' -o -name 'mmww_part*.c' -o -name 'mmww_dispatch.c' -o -name 'mmww_cycles.c' -o -name 'mmww_layout.c' -o -name 'mmww_decls.h' \); bad=1
fi
# generated C announces itself in its first lines ("AUTO-GENERATED ... recompiled code")
while IFS= read -r -d '' f; do
  if head -5 "$f" | grep -qi 'AUTO-GENERATED\|Generated by GenesisRecomp'; then echo "REFUSING: generated C $f"; bad=1; fi
done < <(find "$OUT" \( -name '*.c' -o -name '*.h' \) -print0)
[ $bad -eq 0 ] || { echo "package check FAILED"; exit 1; }
if [ "${MAKE_ZIP:-0}" = 1 ]; then
  VER=$(sed -n 's/^project(.* VERSION \([0-9.]*\).*/\1/p' "$ROOT/CMakeLists.txt")
  ZIP="WilyWars-GenesisRecomp-windows-x64-v$VER.zip"
  ( cd "$ROOT/dist" && rm -f "$ZIP" && python3 -c "import shutil,sys; shutil.make_archive(sys.argv[1][:-4], 'zip', '.', 'WilyWarsRecomp-win64')" "$ZIP" )
  if python3 -c "import zipfile,sys; sys.stdout.write('\n'.join(zipfile.ZipFile(sys.argv[1]).namelist()))" "$ROOT/dist/$ZIP" | grep -Ei '\.(bin|md\.rom|gen|smd|eep|srm|state)$|/generated/|mmww_part[0-9]+\.c' ; then echo "REFUSING: zip has ROM/save/generated files"; exit 1; fi
  echo "zip: $ROOT/dist/$ZIP ($(du -h "$ROOT/dist/$ZIP" | cut -f1)) - local release asset"
fi
echo "package OK: $OUT ($(du -sh "$OUT" | cut -f1), $(find "$OUT" -type f | wc -l) files); no ROM, no generated code"
