#!/usr/bin/env python3
"""Static function-pointer leads for a compiled-C Genesis game.

usage: pointer_leads.py <rom> <executed_pcs.txt> <out.discovery.toml>

The game keeps most code addresses as absolute 32-bit immediates
(move.l #addr / pea addr / lea addr,An / jsr / jmp). Every such immediate that
lands on a PC the interpreter actually executed is written as a function lead.
Addresses only; the recompiler's validator still gates each lead.
"""
import struct, sys
rom = open(sys.argv[1], "rb").read()
pcs = {int(l, 16) for l in open(sys.argv[2]) if l.strip() and not l.startswith("#")}
leads = set()
for off in range(0x200, len(rom) - 6, 2):
    op = struct.unpack(">H", rom[off:off + 2])[0]
    imm = struct.unpack(">I", rom[off + 2:off + 6])[0]
    if imm not in pcs or imm < 0x200 or imm >= 0x200000:
        continue
    is_movel_imm = (op & 0xF03F) == 0x203C         # move.l #imm,<ea>
    is_pea = op == 0x4879
    is_lea = (op & 0xF1FF) == 0x41F9
    is_jsr_jmp = op in (0x4EB9, 0x4EF9)
    if is_movel_imm or is_pea or is_lea or is_jsr_jmp:
        leads.add(imm)
with open(sys.argv[3], "w") as f:
    f.write("# Absolute code-pointer leads that runtime coverage confirmed as executed.\n")
    f.write("# Generated by tools/pointer_leads.py. Addresses only; validator-gated.\n")
    f.write("[functions]\nextra = [\n")
    for a in sorted(leads): f.write("  0x%06X,\n" % a)
    f.write("]\n")
print("pointer leads:", len(leads))
